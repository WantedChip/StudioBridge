"""Piano-roll script (.pyscript) template and renderer.

Per spec 06_l0d_pianoroll_actuation_render.md §1–§3 and [PR-01]..[PR-06].
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import Any, Final

from studiobridge.pianoroll.types import Note

DEFAULT_DEVICE_NAME: Final[str] = "SBridge"

_TEMPLATE: Final[str] = '''# name={device_name} Apply
# Author=StudioBridge
"""Generated FL Studio piano-roll script.

Do not edit manually. Generated by StudioBridge PyscriptGenerator.
"""

import flpianoroll as fpr

NOTES = {notes_literal}
MODE = "{mode}"
RANGE = {range_literal}
JOB = "{job_id}"


def _get_count(obj, attr_name):
    val = getattr(obj, attr_name, 0)
    return val() if callable(val) else val


def apply(form=None):
    score = getattr(fpr, "score", None)
    if score is None:
        score = form
    if score is None:
        raise RuntimeError("flpianoroll.score is not available")

    # 1. Idempotency guard: if a marker with our JOB ID already exists, do nothing
    marker_count = _get_count(score, "markerCount")
    target_marker = "JOB:" + JOB
    for i in range(marker_count):
        m = score.getMarker(i)
        name = getattr(m, "name", "") or ""
        if name == target_marker or name.startswith(target_marker + ":"):
            # Accidental re-run: abort without altering notes
            return

    initial_note_count = _get_count(score, "noteCount")
    deleted_count = 0

    # 2. Clear notes according to MODE
    if MODE == "replace_all":
        if hasattr(score, "clearNotes"):
            try:
                score.clearNotes(True)
            except TypeError:
                score.clearNotes()
        else:
            for i in range(initial_note_count - 1, -1, -1):
                score.deleteNote(i)
        deleted_count = initial_note_count

    elif MODE == "replace_range":
        if RANGE is not None and len(RANGE) == 2:
            start_ticks = int(RANGE[0])
            end_ticks = int(RANGE[1])
            for i in range(initial_note_count - 1, -1, -1):
                n = score.getNote(i)
                t = getattr(n, "time", 0)
                if start_ticks <= t < end_ticks:
                    score.deleteNote(i)
                    deleted_count += 1

    elif MODE == "append":
        pass

    else:
        raise ValueError("Unknown mode: " + str(MODE))

    # 3. Add notes via score.addNote(...)
    for item in NOTES:
        n = fpr.Note()
        n.time = int(item[0])
        n.length = int(item[1])
        n.number = int(item[2])
        n.velocity = float(item[3])
        n.pan = float(item[4])
        n.release = float(item[5])
        n.color = int(item[6])
        n.group = int(item[7])
        n.fcut = float(item[8])
        n.fres = float(item[9])
        n.slide = bool(item[10])
        score.addNote(n)

    # 4. In-script validation: verify post-execution note count
    if MODE == "replace_all":
        expected_count = len(NOTES)
    elif MODE == "replace_range":
        expected_count = initial_note_count - deleted_count + len(NOTES)
    else:  # append
        expected_count = initial_note_count + len(NOTES)

    current_note_count = _get_count(score, "noteCount")
    assert current_note_count == expected_count, (
        "Validation failure: expected "
        + str(expected_count)
        + " notes, got "
        + str(current_note_count)
    )

    # 5. Set status marker indicating successful completion
    status_marker = fpr.Marker()
    status_marker.name = "JOB:" + JOB + ":OK:" + str(len(NOTES))
    if NOTES:
        marker_time = int(NOTES[0][0])
    elif RANGE is not None and len(RANGE) == 2:
        marker_time = int(RANGE[0])
    else:
        marker_time = 0
    status_marker.time = marker_time
    score.addMarker(status_marker)

    # 6. Experimental covert status channel: attempt to rename active pattern
    try:
        import patterns
        current_pat = patterns.patternNumber()
        patterns.setPatternName(current_pat, "JOB:OK:" + str(len(NOTES)))
    except Exception:
        pass


def applyScore(score=None):
    return apply(score)


if __name__ == "__main__":
    apply()
'''


def format_notes_literal(notes: Sequence[Note | tuple[Any, ...]]) -> str:
    """Format notes as a Python literal list of 11-tuples."""
    if not notes:
        return "[]"

    lines: list[str] = ["[\n"]
    for item in notes:
        if isinstance(item, Note):
            t = item.to_tuple()
        elif isinstance(item, Sequence) and len(item) == 11:
            t = (
                int(item[0]),
                int(item[1]),
                int(item[2]),
                round(float(item[3]), 6),
                round(float(item[4]), 6),
                round(float(item[5]), 6),
                int(item[6]),
                int(item[7]),
                round(float(item[8]), 6),
                round(float(item[9]), 6),
                bool(item[10]),
            )
        else:
            t = Note.from_tuple(item).to_tuple()

        lines.append(
            f"    ({t[0]}, {t[1]}, {t[2]}, {t[3]}, {t[4]}, "
            f"{t[5]}, {t[6]}, {t[7]}, {t[8]}, {t[9]}, {t[10]}),\n"
        )
    lines.append("]")
    return "".join(lines)


def render_apply_script(
    job_id: str,
    notes: Sequence[Note | tuple[Any, ...]],
    mode: str = "append",
    time_range: tuple[int, int] | None = None,
    device_name: str = DEFAULT_DEVICE_NAME,
) -> str:
    """Render a complete, self-contained FL Studio piano-roll script (.pyscript).

    Args:
        job_id: Unique idempotency job identifier (e.g. 'sbj-20261025-0001').
        notes: Sequence of Note objects or 11-tuples.
        mode: Edit mode ('append', 'replace_all', or 'replace_range').
        time_range: (start_ticks, end_ticks) range tuple when mode='replace_range'.
        device_name: Brand/device name for script header comment.

    Returns:
        Full UTF-8 Python script source code.
    """
    notes_literal = format_notes_literal(notes)

    if time_range is not None and len(time_range) == 2:
        range_literal = f"({int(time_range[0])}, {int(time_range[1])})"
    else:
        range_literal = "None"

    return _TEMPLATE.format(
        device_name=device_name,
        notes_literal=notes_literal,
        mode=mode,
        range_literal=range_literal,
        job_id=job_id,
    )
