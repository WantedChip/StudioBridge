class TestMcpHostPromptIntegration:
    """Tests verifying JSON-RPC 2.0 protocol dispatch for prompt methods."""

    def _init_host(self, host: McpHost) -> None:
        init_req = {
            "jsonrpc": "2.0",
            "id": 1,
            "method": "initialize",
            "params": {
                "protocolVersion": "2026-07-28",
                "capabilities": {},
                "clientInfo": {"name": "test", "version": "1.0"},
            },
        }
        host.handle_request(init_req)

    def test_jsonrpc_prompts_list(self) -> None:
        """Verify 'prompts/list' JSON-RPC returns all prompt templates."""
        server = StudioMcpServer(toolsets="core")
        self._init_host(server.host)

        req = {
            "jsonrpc": "2.0",
            "id": 20,
            "method": "prompts/list",
            "params": {},
        }
        resp = server.host.handle_request(req)
        assert resp is not None
        assert resp["jsonrpc"] == "2.0"
        assert resp["id"] == 20
        assert "result" in resp

        res = resp["result"]
        assert "prompts" in res
        names = [p["name"] for p in res["prompts"]]
        assert "balance_stems" in names
        assert "inspect_session" in names
        assert "export_preview" in names

    def test_jsonrpc_prompts_get_balance_stems(self) -> None:
        """Verify 'prompts/get' JSON-RPC renders balance_stems messages."""
        server = StudioMcpServer(toolsets="core")
        self._init_host(server.host)

        req = {
            "jsonrpc": "2.0",
            "id": 21,
            "method": "prompts/get",
            "params": {
                "name": "balance_stems",
                "arguments": {"target_headroom_db": "-5.0"},
            },
        }
        resp = server.host.handle_request(req)
        assert resp is not None
        assert resp["id"] == 21
        assert "result" in resp

        res = resp["result"]
        assert "messages" in res
        assert len(res["messages"]) == 1
        msg = res["messages"][0]
        assert msg["role"] == "user"
        assert "-5.0 dB" in msg["content"]["text"]

    def test_jsonrpc_prompts_get_unknown_prompt_returns_error_frame(self) -> None:
        """Unknown prompt name returns INVALID_PARAMS error frame."""
        server = StudioMcpServer(toolsets="core")
        self._init_host(server.host)

        req = {
            "jsonrpc": "2.0",
            "id": 22,
            "method": "prompts/get",
            "params": {"name": "nonexistent_prompt"},
        }
        resp = server.host.handle_request(req)
        assert resp is not None
        assert resp["id"] == 22
        assert "error" in resp
        assert resp["error"]["code"] == JsonRpcErrorCode.INVALID_PARAMS
        assert "not found" in resp["error"]["message"]

    def test_jsonrpc_prompts_get_missing_name_returns_invalid_params(self) -> None:
        """Missing 'name' parameter returns INVALID_PARAMS error frame."""
        server = StudioMcpServer(toolsets="core")
        self._init_host(server.host)

        req = {
            "jsonrpc": "2.0",
            "id": 23,
            "method": "prompts/get",
            "params": {},
        }
        resp = server.host.handle_request(req)
        assert resp is not None
        assert "error" in resp
        assert resp["error"]["code"] == JsonRpcErrorCode.INVALID_PARAMS
