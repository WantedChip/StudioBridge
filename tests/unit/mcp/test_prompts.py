"""Unit and integration tests for Model Context Protocol (MCP) prompt templates.

Verifies:
1. Static prompt catalog: balance_stems, inspect_session, export_preview.
2. Parameter validation and default values.
3. Guided workflow instructions and prompt rendering.
4. JSON-RPC protocol dispatch via prompts/list and prompts/get.
"""

from __future__ import annotations

import pytest

from studiobridge.mcp.host import JsonRpcErrorCode, McpHost
from studiobridge.mcp.prompts import (
    PromptArgument,
    PromptDefinition,
    PromptMessage,
    PromptResult,
    get_default_prompts,
    get_prompt,
)
from studiobridge.mcp.server import StudioMcpServer


class TestPromptDefinitions:
    """Tests verifying prompt definition structures and catalog metadata."""

    def test_default_prompts_catalog(self) -> None:
        """Verify get_default_prompts returns the 3 core prompt templates."""
        prompts = get_default_prompts()
        names = [p.name for p in prompts]
        assert "balance_stems" in names
        assert "inspect_session" in names
        assert "export_preview" in names
        assert len(prompts) == 3

    def test_prompt_argument_serialization(self) -> None:
        """Verify PromptArgument to_mcp_dict matches MCP specification."""
        arg = PromptArgument(
            name="target_headroom_db",
            description="Target peak headroom in dB",
            required=False,
        )
        d = arg.to_mcp_dict()
        assert d["name"] == "target_headroom_db"
        assert d["description"] == "Target peak headroom in dB"
        assert d["required"] is False

    def test_prompt_definition_serialization(self) -> None:
        """Verify PromptDefinition to_mcp_dict matches MCP specification."""
        p = PromptDefinition(
            name="test_prompt",
            description="A test prompt template",
            arguments=[PromptArgument(name="opt", description="An option")],
        )
        d = p.to_mcp_dict()
        assert d["name"] == "test_prompt"
        assert d["description"] == "A test prompt template"
        assert len(d["arguments"]) == 1
        assert d["arguments"][0]["name"] == "opt"

    def test_prompt_message_serialization(self) -> None:
        """Verify PromptMessage to_mcp_dict matches MCP specification."""
        msg = PromptMessage(
            role="user",
            content={"type": "text", "text": "Hello, world!"},
        )
        d = msg.to_mcp_dict()
        assert d["role"] == "user"
        assert d["content"]["type"] == "text"
        assert d["content"]["text"] == "Hello, world!"

    def test_prompt_result_serialization(self) -> None:
        """Verify PromptResult to_mcp_dict matches MCP specification."""
        res = PromptResult(
            description="Result description",
            messages=[PromptMessage(role="user", content={"type": "text", "text": "Run check"})],
        )
        d = res.to_mcp_dict()
        assert d["description"] == "Result description"
        assert len(d["messages"]) == 1
        assert d["messages"][0]["role"] == "user"


class TestPromptRendering:
    """Tests verifying message content generated by prompt templates."""

    def test_render_balance_stems_default(self) -> None:
        """Render balance_stems with default arguments."""
        res = get_prompt("balance_stems")
        assert res.description == "Guided stem balancing workflow"
        assert len(res.messages) == 1

        msg = res.messages[0]
        assert msg.role == "user"
        text = msg.content["text"]
        assert "studio_status" in text
        assert "checkpoint_create" in text
        assert "mixer_set" in text
        assert "-6.0 dB" in text
        assert "allow_protected=true" in text
        assert "write receipts" in text

    def test_render_balance_stems_custom_arguments(self) -> None:
        """Render balance_stems with custom headroom and focus tracks."""
        res = get_prompt(
            "balance_stems",
            {"target_headroom_db": "-4.5", "focus_tracks": "Drums, Bass, Leads"},
        )
        text = res.messages[0].content["text"]
        assert "-4.5 dB" in text
        assert "Drums, Bass, Leads" in text

    def test_render_balance_mix_alias(self) -> None:
        """Verify balance_mix aliases to balance_stems per spec 10_l2_interfaces.md §2.5."""
        res = get_prompt("balance_mix")
        assert res.description == "Guided stem balancing workflow"
